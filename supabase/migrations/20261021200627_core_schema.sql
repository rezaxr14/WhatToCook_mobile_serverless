create index grocery_items_user_id_idx on public.grocery_items (user_id);
create index grocery_items_user_checked_created_idx
  on public.grocery_items (user_id, checked, created_at desc);
create index grocery_items_ingredient_id_idx
  on public.grocery_items (ingredient_id);
create index grocery_items_source_recipe_id_idx
  on public.grocery_items (source_recipe_id);

