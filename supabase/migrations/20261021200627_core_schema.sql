-- ---------------------------------------------------------------------------
-- Profile bootstrap on signup (email or anonymous)
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_username text;
  v_locale text;
  v_plan text;
begin
  v_locale := coalesce(new.raw_user_meta_data ->> 'locale', 'en');
  if v_locale not in ('en', 'tr', 'fa', 'ar', 'es') then
    v_locale := 'en';
  end if;

  v_username := coalesce(
    nullif(pg_catalog.btrim(new.raw_user_meta_data ->> 'username'), ''),
    nullif(pg_catalog.split_part(coalesce(new.email, ''), '@', 1), ''),
    'guest_' || pg_catalog.left(pg_catalog.replace(new.id::text, '-', ''), 8)
  );
  v_username := pg_catalog.regexp_replace(v_username, '[^a-zA-Z0-9_ -]', '', 'g');
  v_username := pg_catalog.left(pg_catalog.btrim(v_username), 24);
  if pg_catalog.char_length(v_username) < 2 then
    v_username := 'user_' || pg_catalog.left(pg_catalog.replace(new.id::text, '-', ''), 8);
  end if;
  if exists (
    select 1 from public.profiles p
    where pg_catalog.lower(p.username) = pg_catalog.lower(v_username)
  ) then
    v_username := pg_catalog.left(v_username, 16) || '_' ||
      pg_catalog.left(pg_catalog.replace(new.id::text, '-', ''), 8);
  end if;

  v_plan := case when new.is_anonymous then 'anonymous' else 'free' end;

  insert into public.profiles (id, username, locale, plan_id)
  values (new.id, v_username, v_locale, v_plan)
  on conflict (id) do nothing;

  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Backfill profiles for users created before this migration (normally none).
insert into public.profiles (id, username, locale, plan_id)
select
  u.id,
  'user_' || pg_catalog.left(pg_catalog.replace(u.id::text, '-', ''), 8),
  'en',
  case when u.is_anonymous then 'anonymous' else 'free' end
from auth.users u
left join public.profiles p on p.id = u.id
where p.id is null
on conflict (id) do nothing;
