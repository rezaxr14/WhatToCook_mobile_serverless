  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  request_id uuid not null,
  feature text not null,
  provider text,
  model text,
  status text not null default 'reserved'
    check (status in ('reserved', 'settled', 'failed', 'refunded')),
  reserved_micro_usd bigint not null default 0
    check (reserved_micro_usd >= 0),
  input_tokens integer check (input_tokens is null or input_tokens >= 0),
  output_tokens integer check (output_tokens is null or output_tokens >= 0),
  cost_micro_usd bigint not null default 0 check (cost_micro_usd >= 0),
  cache_hit boolean not null default false,
  latency_ms integer check (latency_ms is null or latency_ms >= 0),
  error_code text,
  created_at timestamptz not null default now(),
  settled_at timestamptz,
  constraint ai_usage_events_user_request_key unique (user_id, request_id)
);

create index ai_usage_events_user_created_idx
  on public.ai_usage_events (user_id, created_at desc);
create index ai_usage_events_status_created_idx
  on public.ai_usage_events (status, created_at);
