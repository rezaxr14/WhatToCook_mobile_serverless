  on public.pantry_items (user_id) where deleted_at is null;
create index pantry_items_ingredient_id_idx
  on public.pantry_items (ingredient_id);

create table public.grocery_items (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  ingredient_id bigint references public.ingredients (id) on delete set null,
  name text not null,
  category text not null default 'General',
  quantity text not null default '1 item',
