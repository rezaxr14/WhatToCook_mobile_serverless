create table public.ai_model_prices (
  id bigint generated by default as identity primary key,
  provider text not null,
  model text not null,
  -- Price per 1M tokens in micro-USD (1 USD = 1,000,000 micro-USD).
  input_micro_usd_per_million bigint not null
    check (input_micro_usd_per_million >= 0),
  output_micro_usd_per_million bigint not null
    check (output_micro_usd_per_million >= 0),
  active boolean not null default true,
  effective_from timestamptz not null default now(),
  source_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (provider, model, effective_from)
);

create index ai_model_prices_active_idx
  on public.ai_model_prices (provider, model) where active;

