-- Core catalog + user data model for WhatToCook.
-- Owner-scoped tables use RLS (see the next migration). Catalog tables are public read-only.
-- AI metering tables are server-only; clients can read only their own usage rows.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- Shared helpers
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = pg_catalog.now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Plans and profiles
-- ---------------------------------------------------------------------------
create table public.plans (
  id text primary key,
  name text not null,
  -- Per-feature daily request limits. -1 = unlimited, 0 = disabled.
  features jsonb not null default '{}'::jsonb,
  -- Monthly AI budget in micro-USD. -1 = unlimited.
  monthly_budget_micro_usd bigint not null default 0
    check (monthly_budget_micro_usd >= -1),
  max_image_bytes integer not null default 5242880
    check (max_image_bytes > 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint plans_id_format check (id ~ '^[a-z][a-z0-9_-]{1,31}$')
);

insert into public.plans (id, name)
values ('free', 'Free'), ('anonymous', 'Anonymous')
on conflict (id) do nothing;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text not null,
  locale text not null default 'en' check (locale in ('en', 'tr', 'fa', 'ar', 'es')),
  plan_id text not null default 'free' references public.plans (id) on delete restrict,
  telegram_chat_id bigint unique,
  telegram_username text,
  telegram_link_token text unique,
  telegram_link_expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_length check (char_length(username) between 2 and 32)
);

create unique index profiles_username_lower_key
  on public.profiles (lower(username));

create index profiles_plan_id_idx on public.profiles (plan_id);

-- ---------------------------------------------------------------------------
-- Catalog
-- ---------------------------------------------------------------------------
create table public.ingredients (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  -- Localized display names, at minimum {"en": "..."}.
  names jsonb not null default '{}'::jsonb,
  name_en text generated always as (names ->> 'en') stored,
  category text not null default 'General',
  calories_per_100g numeric(8, 2)
    check (calories_per_100g is null or calories_per_100g >= 0),
  image_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ingredients_slug_format
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint ingredients_names_has_en check (names ? 'en')
);

create unique index ingredients_name_en_lower_key
  on public.ingredients (lower(name_en));
create index ingredients_category_idx on public.ingredients (category);

create table public.recipes (
  id bigint generated by default as identity primary key,
  owner_id uuid references public.profiles (id) on delete cascade,
  catalog_key text unique,
  source text not null default 'catalog'
    check (source in ('catalog', 'ai', 'user')),
  title jsonb not null default '{}'::jsonb,
  title_en text generated always as (title ->> 'en') stored,
  description jsonb not null default '{}'::jsonb,
  -- Ordered array of instruction steps, e.g. ["Whisk the eggs.", "Fry gently."].
  instructions jsonb not null default '[]'::jsonb,
  cooking_time_minutes integer
    check (cooking_time_minutes is null or cooking_time_minutes >= 0),
  servings integer check (servings is null or servings > 0),
  image_path text,
  macros jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  constraint recipes_title_has_en check (title ? 'en'),
  constraint recipes_owner_source_check check (
    (owner_id is null and source = 'catalog' and catalog_key is not null)
    or (owner_id is not null and source in ('ai', 'user'))
  )
);

create index recipes_owner_id_idx on public.recipes (owner_id);
create index recipes_catalog_key_idx
  on public.recipes (catalog_key) where catalog_key is not null;
create index recipes_title_en_lower_idx on public.recipes (lower(title_en));
create index recipes_updated_at_idx on public.recipes (updated_at);

create table public.recipe_ingredients (
  id bigint generated by default as identity primary key,
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  ingredient_id bigint not null references public.ingredients (id) on delete restrict,
  quantity text not null default 'to taste',
  unit text not null default 'g',
  optional boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint recipe_ingredients_unique unique (recipe_id, ingredient_id)
);

create index recipe_ingredients_recipe_id_idx
  on public.recipe_ingredients (recipe_id);
create index recipe_ingredients_ingredient_id_idx
  on public.recipe_ingredients (ingredient_id);

