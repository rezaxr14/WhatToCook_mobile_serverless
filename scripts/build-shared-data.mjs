#!/usr/bin/env node
/**
 * Generates the two committed data modules from `dish-catalog.json` and the
 * seed images on disk:
 *
 *   packages/shared/src/dish-catalog.ts    compact catalog for the resolver
 *   packages/shared/src/image-manifest.ts  legacy path -> content-hashed object
 *
 * The JSON file stays the single source of truth; both apps import the
 * generated TypeScript, which keeps Deno and Vite from loading JSON modules.
 */
import { createHash } from 'node:crypto';
import { access, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SEED = join(ROOT, 'supabase', 'seed-images');
const shared = join(ROOT, 'packages', 'shared', 'src');

const catalog = JSON.parse(await readFile(join(ROOT, 'dish-catalog.json'), 'utf8'));
const dishes = Array.isArray(catalog.dishes) ? catalog.dishes : [];

const compact = dishes.map((dish) => ({
  key: dish.key,
  names: dish.names,
  keywords: dish.keywords ?? [],
  cuisine: dish.cuisine,
  group: dish.group,
  photo: dish.files?.[0]?.file ?? null,
}));

// A catalog entry may share its logical filename with a legacy fixed-path
// photo (for example `dishes/risotto.webp`). The catalog always wins: uploading
// the wrong variant would silently replace the verified photo.
const catalogFiles = new Set();
for (const dish of dishes) {
  for (const file of dish.files ?? []) {
    if (!file?.file) continue;
    catalogFiles.add(file.file);
    try {
      await access(join(SEED, file.file));
    } catch {
      throw new Error(`dish-catalog.json references a missing seed image: ${file.file}`);
    }
  }
}

const header =
  '// Generated by scripts/build-shared-data.mjs from dish-catalog.json. Do not edit.\n';
const catalogSource =
  header +
  `export interface CatalogDish {\n  key: string;\n  names: Record<'en' | 'fa' | 'ar' | 'tr' | 'es', string>;\n  keywords: string[];\n  cuisine: string;\n  group: string;\n  /** Content-hashed Storage path of the best photo, or null when only a group photo exists. */\n  photo: string | null;\n}\n\n` +
  `export const DISH_CATALOG: readonly CatalogDish[] = ${JSON.stringify(compact, null, 2)};\n`;
await writeFile(join(shared, 'dish-catalog.ts'), catalogSource);

const manifest = {};
for (const folder of ['recipes', 'dishes', 'ingredients']) {
  const names = await readdir(join(SEED, folder)).catch(() => []);
  const entries = names.map((name) => {
    const match = /^(.*)\.([0-9a-f]{8})\.([a-z0-9]+)$/i.exec(name);
    return {
      name,
      match,
      logical: match ? `${match[1]}.${match[3]}` : name,
    };
  });

  const byLogical = new Map();
  for (const entry of entries) {
    const list = byLogical.get(entry.logical) ?? [];
    list.push(entry);
    byLogical.set(entry.logical, list);
  }

  for (const [logical, candidates] of byLogical) {
    const hashed = candidates.filter((entry) => entry.match);
    const fromCatalog = candidates.find((entry) =>
      catalogFiles.has(`${folder}/${entry.name}`),
    );
    if (hashed.length > 1 && !fromCatalog) {
      console.warn(
        `multiple content-hashed copies of ${folder}/${logical}; pick one in dish-catalog.json to make the manifest deterministic`,
      );
    }
    const chosen =
      fromCatalog ??
      (hashed.length === 1
        ? hashed[0]
        : hashed.length > 0
          ? [...hashed].sort((a, b) => a.name.localeCompare(b.name))[0]
          : candidates[0]);

    manifest[`${folder}/${logical}`] = `${folder}/${chosen.name}`;

    if (!chosen.match) {
      // First run: the file still has its legacy name; keep it in the manifest
      // as-is so the hint below can be actioned, but never guess a hash.
      const bytes = await readFile(join(SEED, folder, chosen.name));
      const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8);
      console.warn(`seed image ${folder}/${chosen.name} is not content-hashed (sha256 ${hash})`);
    }

    for (const entry of hashed) {
      const bytes = await readFile(join(SEED, folder, entry.name));
      const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8);
      if (hash !== entry.match[2].toLowerCase()) {
        console.warn(`seed image ${folder}/${entry.name} hash mismatch (actual ${hash})`);
      }
    }
  }
}

const manifestSource =
  header +
  `export const IMAGE_MANIFEST: Readonly<Record<string, string>> = ${JSON.stringify(manifest, null, 2)};\n\n` +
  `/** Map a logical catalog path to its content-hashed Storage object. */\nexport function resolveImagePath(path: string): string {\n  return IMAGE_MANIFEST[path] ?? path;\n}\n`;
await writeFile(join(shared, 'image-manifest.ts'), manifestSource);

console.log(`wrote ${dishes.length} dishes and ${Object.keys(manifest).length} image aliases`);
